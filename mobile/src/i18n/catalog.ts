const catalogs: Record<MobileLocale, Record<TranslationKey, string>> = {
  'zh-CN': zhCN,
  'zh-TW': zhTW,
  en,
  ja,
};

export type TranslationParams = Record<string, string | number>;
export type Translator = (
  key: TranslationKey,
  params?: TranslationParams,
) => string;

export function isMobileLocale(value: unknown): value is MobileLocale {
  return supportedLocales.some(item => item.locale === value);
}

export function normalizeMobileLocale(value: unknown): MobileLocale {
  if (typeof value !== 'string') return defaultLocale;
  const normalized = value.trim().replace(/_/g, '-').toLowerCase();
  if (normalized === 'zh-tw' || normalized === 'zh-hant') return 'zh-TW';
  if (normalized === 'zh' || normalized === 'zh-cn' || normalized === 'zh-hans') {
    return 'zh-CN';
  }
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en';
  if (normalized === 'ja' || normalized.startsWith('ja-')) return 'ja';
  return defaultLocale;
}

export function getLocaleNativeName(locale: MobileLocale) {
  return (
    supportedLocales.find(item => item.locale === locale)?.nativeName || locale
  );
}

export function translate(
  locale: MobileLocale,
  key: TranslationKey,
  params?: TranslationParams,
) {
  const template = catalogs[locale][key] || catalogs[defaultLocale][key];
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name)
      ? String(params[name])
      : match,
  );
}

export function createTranslator(locale: MobileLocale): Translator {
  return (key, params) => translate(locale, key, params);
}
